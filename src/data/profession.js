export function rareProfession() {
  let rareProff;
  const randomValue2 = Math.floor(Math.random() * 100) + 1;

  if (randomValue2 >= 51) {
    rareProff = `(початківець)`;
  } else if (randomValue2 >= 26) {
    rareProff = `(любитель)`;
  } else if (randomValue2 >= 16) {
    rareProff = `(професіонал)`;
  } else if (randomValue2 >= 8) {
    rareProff = `(майстер)`;
  } else if (randomValue2 >= 4) {
    rareProff = `(гуру)`;
  } else {
    rareProff = `(початківець)`;
  }

  return rareProff;
}
