export function generateDisasterAndBunker(totalPlayers) {
  const disaster = getRandom(disasterTypes);
  const size = getRandom(bunkerSizes);

  const timeValue = Math.floor(Math.random() * 11) + 1;
  const timeString = `${timeValue} ${getYearDeclension(timeValue)}`;

  const randomItemsCount = Math.floor(Math.random() * 4);
  let additionalItems = [];
  additionalItems.push("Стандарт: запас їжі на місяць");
  if (randomItemsCount === 0) {
    additionalItems.push("Нічого особливого не знайдено");
  } else {
    let tempQuirky = [...quirkyItems];
    for (let i = 0; i < randomItemsCount; i++) {
      const item = getRandom(tempQuirky);
      additionalItems.push(item);
      tempQuirky = tempQuirky.filter((e) => e !== item);
    }
  }
  const totalSpaces = Math.floor(totalPlayers / 2);

  const itemsList = [...additionalItems]
    .map((item) => `<li>${item}</li>`)
    .join("");

  return {
    disasterImage: disaster.image,
    disasterTitle: disaster.title,
    disasterImpact: disaster.impact,
    bunkerSizeTitle: size.title,
    bunkerSizeCapacity: size.capacity,
    staytime: timeString,
    totalSpaces: totalSpaces,
    inventory: itemsList,
  };
}
